# graphd/gd/confusables.py — TR39 skeleton 同形字骨架表（WRAP-3 族 4）
# 用途: denylist 红线扫描的域名/文本归一折叠——跨脚本同形字(西里尔/希腊↔拉丁)在 NFKC 下
# 不折叠(gatewarden #20 实证: ο↔o 非 compatibility 映射), 词边界正则按码点比对必然漏检。
# 表形态(vendored 缩减集): **ICANN/Unicode 官方 confusables 数据(full confusables.txt 约
# 5 万+映射)的跨脚本高频骨架子集**——覆盖如实注记: 本表为 TR39 skeleton 缩减集而非全表,
# 未收录同形字仍可逃逸=登记残余(闭合需全量 vendored 数据文件, 依赖体量归用户拍板)。
# 零网络运行时依赖(纯 vendored dict); 与 NFKC 层(#20 已修)互补: NFKC 折兼容分解, 本表折
# 跨脚本同形, 两层串联覆盖。

_SKELETON = {
    # ── cyrillic → latin(高频混淆: а е о р с у х к і 及扩展) ──
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
    "і": "i", "ј": "j", "ѕ": "s", "ә": "a", "ғ": "g", "қ": "k", "ң": "h",
    "һ": "h", "ƅ": "b", "ԛ": "q", "ԝ": "w", "ӏ": "i", "ґ": "g", "ћ": "h",
    "љ": "j", "њ": "n", "џ": "u", "ҋ": "j", "ӑ": "a", "ӗ": "e", "ӧ": "o",
    # ── greek → latin ──
    "ο": "o", "ν": "v", "α": "a", "ε": "e", "ρ": "p", "τ": "t", "υ": "u",
    "κ": "k", "ι": "i", "η": "n", "μ": "m", "ω": "w", "β": "b", "χ": "x",
    # ── 域名分隔/标点同形(NFKC 不折叠的 CJK 句点形态; 全角句点已在 #8 由显式归一覆盖) ──
    "。": ".", "．": ".", "｡": ".", "․": ".", "﹒": ".", "．": ".",
    "－": "-", "–": "-", "—": "-",
}


def skeleton_fold(text):
    """同形字骨架折叠(纯函数): 非白名单码点查表→拉丁骨架; 其余原样。

    与调用方的 lower() 顺序无耦合(表内键均为小写/符号形态, 调用方先 lower 亦可)。"""
    if not text:
        return text
    return "".join(_SKELETON.get(ch, ch) for ch in str(text))
